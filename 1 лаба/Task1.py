def calc_expr(s):
    """Рекурсивно вычисляет значение целочисленного выражения.

    Выражение определяется следующим образом:
    <выражение> ::= <цифра> | <выражение> + <цифра> |
    <выражение> − <цифра>

    :param s: строка с выражением без пробелов
    :return: результат вычисления выражения
    """
    if not s:
        return 0
    
    idxplus = s.rfind('+')
    idxminus = s.rfind('-')
    
    if idxplus > idxminus:
        left = s[:idxplus]
        right = s[idxplus + 1:]
        return calc_expr(left) + int(right)  
    elif idxminus != -1:
        left = s[:idxminus]
        right = s[idxminus + 1:]
        return calc_expr(left) - int(right)  
    else:
        return int(s)
        

#данные
exprs = [
    "5",       # цифра
    "5+3",     # сложение
    "5-3",     # вычитание
    "5+3-2",   # комбинация сложения и вычитания
    "1+2+3+4", # много сложений
    "3-2-2",  # много вычитаний
    "5-4+3-2+1", # много комбинаций
    input('введите выражение: ')
]

for expr in exprs:
    print(f"Выражение: {expr}")
    print(f"Результат: {calc_expr(expr)}")
    print()
    
    